def article(number, title, text, penalty=None, status="действует"):
    return {
        "number": number,
        "title": title,
        "text": text,
        "penalty": penalty,
        "status": status
    }

def section(number, title, items):
    return {
        "number": number,
        "title": title,
        "articles": [
            article(n, t, x, p) for n, t, x, p in items
        ]
    }

